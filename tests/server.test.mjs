import { test } from 'node:test';
import http from 'node:http';
import assert from 'node:assert/strict';
import { createApp } from '../server.mjs';
import { Accounts } from '../accounts.mjs';
import { Campaign } from '../campaign.mjs';
test('failed Discord verification prevents start and never creates a campaign', async t => {
  let starts = 0;
  const accounts = new Accounts(() => { starts++; return new Campaign(); });
  const server = createApp(accounts, async () => { throw new Error('Введите действующий токен: Discord отклонил вход.'); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }));
  const url = `http://127.0.0.1:${server.address().port}`;
  const { key } = await (await fetch(`${url}/api/session`)).json();
  const token = 'invalid-test-token-'.repeat(3);
  const headers = { 'X-Local-Key': key, 'Content-Type': 'application/json', 'X-Client-Id': 'integration-client-123' };
  for (const action of ['verify', 'start']) {
    const response = await fetch(`${url}/api/${action}`, { method: 'POST', headers, body: JSON.stringify({ id: 'account-000000001', token, channels: ['123456789012345678'], message: 'Must not send', interval: 60 }) });
    assert.equal(response.status, 400);
    const body = await response.text();
    assert.match(body, /Discord/); assert.ok(!body.includes(token));
  }
  assert.equal(starts, 0); assert.deepEqual(accounts.snapshot(), { accounts: [] });
});
test('local API: protection, multi-account lifecycle, token exclusion', async t => {
  const accounts = new Accounts(() => new Campaign({ fetcher: async () => ({ ok: true }) })); const server = createApp(accounts, async () => ({ id: '123456789012345678', username: 'test' }));
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }));
  const url = `http://127.0.0.1:${server.address().port}`;
  const page = await fetch(url); assert.equal(page.status, 200); const html = await page.text(); assert.match(html, /TradeDesk/); assert.doesNotMatch(html, /id="demo"|id="consent"|Предпросмотр|Личный аккаунт — ваш риск/);
  assert.match(page.headers.get('content-security-policy'), /frame-ancestors 'none'/);
  assert.match(page.headers.get('content-security-policy'), /img-src[^;]*https:\/\/cdn\.discordapp\.com/);
  const favicon = await fetch(`${url}/favicon.svg`); assert.equal(favicon.status, 200); assert.match(favicon.headers.get('content-type'), /^image\/svg\+xml/); assert.match(await favicon.text(), /<svg/);
  assert.equal((await fetch(`${url}/api/status`)).status, 403);
  assert.equal((await fetch(`${url}/api/session`, { headers: { Origin: 'https://attacker.example' } })).status, 403);
  const invalidHostStatus = await new Promise((resolve, reject) => { const request = http.get(`${url}/api/session`, { headers: { Host: 'attacker.example' } }, response => { response.resume(); resolve(response.statusCode); }); request.on('error', reject); });
  assert.equal(invalidHostStatus, 403);
  const { key, apiVersion } = await (await fetch(`${url}/api/session`)).json();
  assert.equal(apiVersion, 2, 'client must detect outdated server before submitting credentials');
  const headers = { 'X-Local-Key': key, 'Content-Type': 'application/json', 'X-Client-Id': 'integration-client-123' };
  const post = (path, data) => fetch(`${url}/api/${path}`, { method: 'POST', headers, body: JSON.stringify(data) });
  assert.equal((await post('start', { demo: true })).status, 400);
  assert.equal((await post('start', null)).status, 400);
  assert.equal((await fetch(`${url}/api/start`, { method: 'POST', headers, body: '{' })).status, 400);
  const verified = await (await post('verify', { token: 'a'.repeat(30) })).json(); assert.equal(verified.user.username, 'test'); assert.ok(!JSON.stringify(verified).includes('a'.repeat(30)));
  assert.doesNotMatch(html, /data-field="name"|data-field="server"/); assert.match(html, /class="settings" hidden disabled/);
  const a = { id: 'account-000000001', channels: ['123456789012345678', '987654321098765432'], message: 'Объявление A', interval: 60, token: 'a'.repeat(30) };
  const b = { ...a, id: 'account-000000002', name: 'Второй', server: 'B', token: 'b'.repeat(30) };
  assert.equal((await post('start', a)).status, 200); assert.equal((await post('start', b)).status, 200);
  await new Promise(r => setImmediate(r));
  const status = await (await fetch(`${url}/api/status`, { headers })).json();
  assert.equal(status.accounts.length, 2); assert.ok(status.accounts.every(a => a.running && a.sent === 1)); assert.ok(!JSON.stringify(status).includes(b.token));
  assert.equal((await post('start', a)).status, 400);
  const stopped = await (await post('stop', { id: a.id })).json(); assert.equal(stopped.accounts[0].running, false); assert.equal(stopped.accounts[1].running, true); assert.equal(accounts.get(a.id).campaign.token, '');
  assert.deepEqual((await (await post('clear', { id: a.id })).json()).accounts[0].events, []);
  assert.equal((await (await post('remove', { id: a.id })).json()).accounts.length, 1);
  assert.ok((await (await post('stop-all', {})).json()).accounts.every(a => !a.running));
  assert.equal((await fetch(`${url}/../package.json`)).status, 404);
});
